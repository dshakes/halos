// OpenAPI builds the OpenAPI 3.1 description of this server's HTTP API.
//
// What is generated and what is written down:
//   - the permission each cookie route needs comes from routePerms and the roles
//     that hold it from rolePerms, so they cannot be mistyped here;
//   - request and response schemas come from the Go types the handlers use
//     (openapi_schema.go), so a new field appears on the next generation;
//   - paths, summaries, query parameters, status codes and examples live in the
//     apiOps table (openapi_ops.go). TestOpenAPI* pin that table to the mux
//     (every registered route is documented, every documented route exists),
//     to routePerms, to the Go types (examples decode strictly) and to the
//     live handlers (every operation is called and must answer a documented
//     status with a body matching its schema).
//
// api/openapi.yaml is this function's output; `make openapi` rewrites it and
// TestOpenAPIFileCurrent fails while it is stale.
func OpenAPI() ([]byte, error) {
	doc, err := openAPIDoc()
	if err != nil {
		return nil, err
	}
	n, err := yamlNode(doc)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	buf.WriteString("# Generated by `make openapi` from internal/server (OpenAPI()). Do not edit.\n" +
		"# Drift is caught by `go test ./internal/server -run OpenAPI`.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(n); err != nil {
		return nil, err
	}
	return buf.Bytes(), enc.Close()
}

var openAPIOnce struct {
	sync.Once
	b   []byte
	err error
}

// openAPICached is what GET /api/v1/openapi.yaml serves: built once, it never changes at runtime.
func openAPICached() ([]byte, error) {
	openAPIOnce.Do(func() { openAPIOnce.b, openAPIOnce.err = OpenAPI() })
	return openAPIOnce.b, openAPIOnce.err
}

// getOpenAPI serves the spec. Public and read-only: it is the same file the
// repository publishes, it describes routes and not data, and API gateways and
// code generators fetch it without credentials (see docs: reference/api).
func (s *Server) getOpenAPI(w http.ResponseWriter, _ *http.Request) {
	b, err := openAPICached()
	if err != nil {
		s.cfg.Log.Error("openapi", "err", err)
		apiErr(w, http.StatusInternalServerError, "openapi unavailable")
		return
	}
	w.Header().Set("Content-Type", "application/yaml; charset=utf-8")
	_, _ = w.Write(b)
}

