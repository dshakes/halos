// openAPIDoc assembles the document as plain JSON-shaped values.
func openAPIDoc() (map[string]any, error) {
	g := newSchemaGen()
	g.comps["Error"] = map[string]any{
		"type": "object", "required": []string{"error"},
		"properties": map[string]any{"error": map[string]any{"type": "string", "description": "A human-readable message. Match on the HTTP status, not on the text."}},
		"example":    map[string]any{"error": "login required"},
	}
	g.comps["OAuthError"] = map[string]any{
		"type": "object", "required": []string{"error"},
		"properties": map[string]any{
			"error":             map[string]any{"type": "string", "description": "RFC 6749 section 5.2 error code, for example invalid_request or slow_down."},
			"error_description": map[string]any{"type": "string"},
		},
	}
	g.comps["ScimError"] = map[string]any{
		"type": "object", "required": []string{"schemas", "status", "detail"},
		"properties": map[string]any{
			"schemas":  map[string]any{"type": "array", "items": map[string]any{"type": "string"}, "description": "urn:ietf:params:scim:api:messages:2.0:Error"},
			"status":   map[string]any{"type": "string", "description": "The HTTP status as a string (RFC 7644 section 3.12)."},
			"scimType": map[string]any{"type": "string"},
			"detail":   map[string]any{"type": "string"},
		},
	}
	g.comps["ScimResource"] = map[string]any{"type": "object", "additionalProperties": true,
		"description": "A SCIM 2.0 User or Group (RFC 7643). Halos keeps userName, displayName, name, emails, active, externalId, members and meta."}
	g.comps["ScimList"] = map[string]any{"type": "object", "additionalProperties": true,
		"description": "A SCIM ListResponse (RFC 7644 section 3.4.2): totalResults, startIndex, itemsPerPage, Resources."}

	paths := map[string]any{}
	seenIDs := map[string]string{}
	for _, o := range apiOps {
		method, path, ok := strings.Cut(o.route, " ")
		if !ok {
			return nil, fmt.Errorf("apiOps: %q is not \"METHOD /path\"", o.route)
		}
		if prev, dup := seenIDs[o.id]; dup {
			return nil, fmt.Errorf("apiOps: operationId %s is used by %s and %s", o.id, prev, o.route)
		}
		seenIDs[o.id] = o.route
		item, _ := paths[path].(map[string]any)
		if item == nil {
			item = map[string]any{}
			paths[path] = item
		}
		item[strings.ToLower(method)] = o.operation(g)
	}
	if len(g.errs) > 0 {
		return nil, fmt.Errorf("openapi schemas: %w", joinErrs(g.errs))
	}
	comps := map[string]any{
		"schemas":         g.comps,
		"securitySchemes": securitySchemes(),
		"responses": map[string]any{
			"Unauthorized": errResponse("No valid session cookie or service-account token. Sign in again, or mint a new token."),
			"Forbidden": errResponse("The caller lacks the permission in x-halo-permission, or a state-changing request came from another origin. " +
				"Audited as authz.deny."),
			"TooManyRequests": errResponse("Too many failed authentications from this client address. Honour Retry-After."),
		},
	}
	return map[string]any{
		"openapi":           "3.1.0",
		"jsonSchemaDialect": "https://json-schema.org/draft/2020-12/schema",
		"info": map[string]any{
			"title":   "Halos halo-server API",
			"version": "v1",
			"description": "The HTTP API of halo-server: the admin console's API, the fleet and gateway endpoints, enrollment, workload token exchange and SCIM.\n\n" +
				"Generated from the server's Go source (`make openapi`); a test fails when it drifts from the routes, RBAC table or response types. " +
				"Errors are `{\"error\": \"...\"}` with the HTTP status carrying the meaning; the token endpoint and SCIM use their RFCs' error bodies. " +
				"Every response carries `X-Request-Id`. API responses carry `Cache-Control: no-store`.\n\n" +
				"Stability: operations marked `x-halo-stability: stable` follow the HTTP API promise in the support policy " +
				"(fields are added in minors, never removed or retyped under `/api/v1`). `experimental` operations back the web console " +
				"or expose policy-shaped documents and may change in a minor release with a CHANGELOG note.\n\n" +
				"Authorization: `x-halo-permission` names the RBAC permission a session-authenticated operation needs; " +
				"`x-halo-roles` (top level) lists the roles that hold each permission.",
			"license": map[string]any{"name": "Apache-2.0", "identifier": "Apache-2.0"},
		},
		"servers":      []any{map[string]any{"url": "/", "description": "The halo-server origin."}},
		"tags":         tagList(),
		"paths":        paths,
		"components":   comps,
		"x-halo-roles": rolePermsDoc(),
	}, nil
}

func joinErrs(errs []error) error {
	var sb strings.Builder
	for i, e := range errs {
		if i > 0 {
			sb.WriteString("; ")
		}
		sb.WriteString(e.Error())
	}
	return fmt.Errorf("%s", sb.String())
}

func errResponse(desc string) map[string]any {
	return map[string]any{"description": desc, "content": map[string]any{"application/json": map[string]any{"schema": ref("Error")}}}
}

func ref(name string) map[string]any { return map[string]any{"$ref": "#/components/schemas/" + name} }

// rolePermsDoc is rolePerms by permission: which roles hold it.
func rolePermsDoc() map[string]any {
	out := map[string]any{}
	for _, x := range []perm{permSession, permRead, permOperate, permApprove, permAudit, permAdmin} {
		roles := []any{}
		if x == permSession {
			roles = append(roles, "any signed-in principal")
		}
		for _, r := range Roles {
			if slices.Contains(rolePerms[r], x) {
				roles = append(roles, r)
			}
		}
		out[string(x)] = roles
	}
	return out
}

