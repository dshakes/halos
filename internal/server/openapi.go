// ---- YAML rendering ----

// keyOrder puts the keys readers look for first; everything else follows
// alphabetically, and map keys that are names (properties, paths, ...) are
// alphabetical throughout.
var keyOrder = func() map[string]int {
	m := map[string]int{}
	for i, k := range []string{
		"openapi", "jsonSchemaDialect", "info", "servers", "tags", "paths", "components",
		"title", "version", "operationId", "summary", "description", "x-halo-permission", "x-halo-stability", "security", "parameters", "requestBody", "responses",
		"name", "in", "required", "$ref", "type", "format", "properties", "items", "additionalProperties", "oneOf", "content", "schema", "example",
		"get", "put", "post", "patch", "delete",
	} {
		m[k] = i + 1
	}
	return m
}()

// nameMaps hold arbitrary names as keys: sorted alphabetically, not by keyOrder.
var nameMaps = map[string]bool{"properties": true, "paths": true, "schemas": true, "responses": true, "securitySchemes": true, "headers": true, "x-halo-roles": true}

// yamlNode renders v (JSON-shaped) with a stable, readable key order.
func yamlNode(v any) (*yaml.Node, error) {
	// A JSON round trip normalises every Go value (slices, ints) to JSON shapes.
	b, err := json.Marshal(v)
	if err != nil {
		return nil, err
	}
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.UseNumber()
	var norm any
	if err := dec.Decode(&norm); err != nil {
		return nil, err
	}
	return toNode(norm, false), nil
}

func toNode(v any, byName bool) *yaml.Node {
	switch x := v.(type) {
	case map[string]any:
		keys := make([]string, 0, len(x))
		for k := range x {
			keys = append(keys, k)
		}
		sort.Slice(keys, func(i, j int) bool {
			ri, rj := keyOrder[keys[i]], keyOrder[keys[j]]
			if byName || ri == 0 && rj == 0 {
				return keys[i] < keys[j]
			}
			if ri == 0 || rj == 0 {
				return ri != 0
			}
			return ri < rj
		})
		n := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
		for _, k := range keys {
			kn := &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: k}
			n.Content = append(n.Content, kn, toNode(x[k], nameMaps[k]))
		}
		return n
	case []any:
		n := &yaml.Node{Kind: yaml.SequenceNode, Tag: "!!seq"}
		for _, e := range x {
			n.Content = append(n.Content, toNode(e, false))
		}
		return n
	case string:
		n := &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: x}
		if strings.Contains(x, "\n") {
			n.Style = yaml.LiteralStyle
		}
		return n
	case json.Number:
		tag := "!!int"
		if strings.ContainsAny(x.String(), ".eE") {
			tag = "!!float"
		}
		return &yaml.Node{Kind: yaml.ScalarNode, Tag: tag, Value: x.String()}
	case bool:
		return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!bool", Value: strconv.FormatBool(x)}
	case nil:
		return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!null", Value: "null"}
	}
	panic(fmt.Sprintf("openapi: unexpected %T", v))
}
