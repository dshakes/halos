// ---- operations ----

type authKind int

const (
	authSession   authKind = iota // routePerms route: session cookie or service token
	authNone                      // public
	authFleet                     // fleet token or device token
	authDevice                    // device token
	authGateway                   // gateway token
	authSCIM                      // SCIM token
	authWorkload                  // Halos-signed credential
	authSignature                 // webhook HMAC
)

func (a authKind) security() []any {
	req := func(names ...string) []any {
		out := make([]any, 0, len(names))
		for _, n := range names {
			out = append(out, map[string]any{n: []any{}})
		}
		return out
	}
	switch a {
	case authSession:
		return req("sessionCookie", "serviceToken")
	case authFleet:
		return req("fleetToken", "deviceToken")
	case authDevice:
		return req("deviceToken")
	case authGateway:
		return req("gatewayToken")
	case authSCIM:
		return req("scimToken")
	case authWorkload:
		return req("workloadToken")
	case authSignature:
		return req("webhookSignature")
	}
	return []any{} // public: no credential in the header or cookie
}

// body documents one request or response body. typ is a value of the Go type
// the handler decodes into or encodes from (nil: no schema beyond the media
// type); example is JSON, or the literal text for non-JSON media types.
type body struct {
	ct      string // media type; default application/json
	typ     any
	one     []any // oneOf alternatives instead of typ
	example string
	desc    string
}

// res is a documented response.
type res struct {
	code int
	body
	hdr map[string]string // header name -> description
}

// query is one query parameter.
type query struct {
	name, desc string
	typ        string // string (default), integer, boolean
	required   bool
	min, max   int
	enum       []string
}

// apiOp documents one registered route. route is the mux pattern.
type apiOp struct {
	route, id, tag, summary string
	desc                    string
	auth                    authKind
	experimental            bool
	query                   []query
	req                     *body
	reqOptional             bool
	ok                      []res          // success responses
	errs                    map[int]string // other statuses, all with the error body of errKind
	errKind                 string         // Error (default), OAuthError, ScimError
	note                    string         // appended to the permission line
}

var pathParamDocs = map[string]string{
	"id":       "The resource id.",
	"name":     "The resource name as written in policy.",
	"launcher": "One of devcontainer, codespaces, coder, laptop.",
}

var braceRE = regexp.MustCompile(`\{([a-zA-Z]+)\}`)

func (o apiOp) operation(g *schemaGen) map[string]any {
	_, path, _ := strings.Cut(o.route, " ")
	op := map[string]any{"operationId": o.id, "summary": o.summary, "tags": []any{o.tag}}
	desc := o.desc
	if need, guarded := routePerms[o.route]; guarded {
		op["x-halo-permission"] = string(need)
		if desc != "" {
			desc += "\n\n"
		}
		desc += "Requires the `" + string(need) + "` permission."
		if o.note != "" {
			desc += " " + o.note
		}
	}
	if desc != "" {
		op["description"] = desc
	}
	if o.experimental {
		op["x-halo-stability"] = "experimental"
	} else {
		op["x-halo-stability"] = "stable"
	}
	op["security"] = o.auth.security()

	var params []any
	for _, m := range braceRE.FindAllStringSubmatch(path, -1) {
		params = append(params, map[string]any{"name": m[1], "in": "path", "required": true, "description": pathParamDocs[m[1]], "schema": map[string]any{"type": "string"}})
	}
	for _, q := range o.query {
		s := map[string]any{"type": cmpOr(q.typ, "string")}
		if q.min != 0 || q.max != 0 {
			s["minimum"], s["maximum"] = q.min, q.max
		}
		if len(q.enum) > 0 {
			s["enum"] = q.enum
		}
		p := map[string]any{"name": q.name, "in": "query", "description": q.desc, "schema": s}
		if q.required {
			p["required"] = true
		}
		params = append(params, p)
	}
	if params != nil {
		op["parameters"] = params
	}
	if o.req != nil {
		rb := map[string]any{"content": o.req.content(g)}
		if !o.reqOptional {
			rb["required"] = true
		}
		if o.req.desc != "" {
			rb["description"] = o.req.desc
		}
		op["requestBody"] = rb
	}

	responses := map[string]any{}
	for _, r := range o.ok {
		d := map[string]any{"description": cmpOr(r.desc, http.StatusText(r.code))}
		if c := r.content(g); c != nil {
			d["content"] = c
		}
		if len(r.hdr) > 0 {
			h := map[string]any{}
			for k, v := range r.hdr {
				h[k] = map[string]any{"description": v, "schema": map[string]any{"type": "string"}}
			}
			d["headers"] = h
		}
		responses[strconv.Itoa(r.code)] = d
	}
	errSchema := ref(cmpOr(o.errKind, "Error"))
	ect := "application/json"
	if o.errKind == "ScimError" {
		ect = "application/scim+json"
	}
	for code, d := range o.errs {
		responses[strconv.Itoa(code)] = map[string]any{"description": d, "content": map[string]any{ect: map[string]any{"schema": errSchema}}}
	}
	if o.auth == authSession {
		responses["401"] = map[string]any{"$ref": "#/components/responses/Unauthorized"}
		responses["403"] = map[string]any{"$ref": "#/components/responses/Forbidden"}
	}
	if _, has := responses["429"]; !has && o.auth != authSession && o.auth != authNone {
		responses["429"] = map[string]any{"$ref": "#/components/responses/TooManyRequests"}
	}
	op["responses"] = responses
	return op
}

func cmpOr[T comparable](a, b T) T {
	var zero T
	if a != zero {
		return a
	}
	return b
}

// content builds a media-type map; nil when there is nothing to describe.
func (b body) content(g *schemaGen) map[string]any {
	ct := cmpOr(b.ct, "application/json")
	if b.typ == nil && len(b.one) == 0 && b.example == "" && b.ct == "" {
		return nil
	}
	mt := map[string]any{}
	switch {
	case len(b.one) > 0:
		var alts []any
		for _, t := range b.one {
			alts = append(alts, g.schema(reflect.TypeOf(t)))
		}
		mt["schema"] = map[string]any{"oneOf": alts}
	case b.typ != nil:
		mt["schema"] = g.schema(reflect.TypeOf(b.typ))
	case ct != "application/json":
		mt["schema"] = map[string]any{"type": "string"}
	}
	if b.example != "" {
		if strings.Contains(ct, "json") {
			var v any
			if err := json.Unmarshal([]byte(b.example), &v); err != nil {
				g.fail("example for %q is not JSON: %v", b.example, err)
			}
			mt["example"] = v
		} else {
			mt["example"] = b.example
		}
	}
	return map[string]any{ct: mt}
}

