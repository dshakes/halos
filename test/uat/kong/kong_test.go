		check(t, g, "spoofed x-halo-* and identity headers are stripped; cohort comes from the verified JWT", r.code == 200 && clean,
			"upstream saw x-halo-ring=%q release=%q experiment=%q variant=%q custom=%q killswitch=%q x-acme-user=%q",
			got.h("x-halo-ring"), got.h("x-halo-release"), got.h("x-halo-experiment"), got.h("x-halo-variant"), got.h("x-halo-custom"), got.h("x-halo-killswitch"), got.h("x-acme-user"))

