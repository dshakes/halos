// ---- report ----

type row struct {
	group, name, evidence string
	pass                  bool
}

var (
	rowsMu sync.Mutex
	rows   []row
)

// check records one scenario outcome (and fails the test without stopping it, so the
// report always covers every scenario).
func check(t *testing.T, group, name string, ok bool, format string, a ...any) {
	t.Helper()
	ev := strings.ReplaceAll(fmt.Sprintf(format, a...), "|", `\|`)
	rowsMu.Lock()
	rows = append(rows, row{group, name, ev, ok})
	rowsMu.Unlock()
	if !ok {
		t.Errorf("FAIL %s: %s: %s", group, name, ev)
	}
}

func TestMain(m *testing.M) {
	code := m.Run()
	writeReport(code == 0)
	os.Exit(code)
}

func writeReport(allPass bool) {
	var b strings.Builder
	verdict := "PASS"
	if !allPass {
		verdict = "FAIL"
	}
	fmt.Fprintf(&b, "# halo-kong in real Kong OSS: UAT report\n\n")
	fmt.Fprintf(&b, "Generated by `make uat-kong` (`scripts/uat-kong.sh`, `test/uat/kong`) on %s. Overall: **%s**.\n\n", time.Now().UTC().Format(time.RFC3339), verdict)
	fmt.Fprintf(&b, "| | |\n|---|---|\n| Kong | `%s` (OSS, db-less, declarative config) |\n| Image | `%s` |\n", getenv("UAT_KONG_VERSION", "unknown"), getenv("UAT_KONG_IMAGE", "unknown"))
	fmt.Fprintf(&b, "| Plugin | `halo-kong` as a Go plugin server (go-pdk), built from this tree |\n| Config | `halo gateway deck` from `examples/acme-corp` + `test/uat/kong/policy` |\n| Upstreams | two mock model servers (`test/uat/mock`) |\n\n")
	fmt.Fprintf(&b, "Kong Enterprise is **UNVERIFIED**: only the OSS image was run.\n\n")
	group := ""
	for _, r := range rows {
		if r.group != group {
			group = r.group
			fmt.Fprintf(&b, "\n## %s\n\n| Scenario | Result | Evidence |\n|---|---|---|\n", group)
		}
		res := "PASS"
		if !r.pass {
			res = "**FAIL**"
		}
		fmt.Fprintf(&b, "| %s | %s | %s |\n", r.name, res, r.evidence)
	}
	if err := os.WriteFile("../KONG-REPORT.md", []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "write report:", err)
	}
}

// ---- plumbing ----

var kongClient = &http.Client{
	Timeout:       60 * time.Second,
	Transport:     &http.Transport{TLSClientConfig: &tls.Config{InsecureSkipVerify: true}}, //nolint:gosec // Kong's generated self-signed cert
	CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse },
}

type reply struct {
	code int
	hdr  http.Header
	body string
}

func (r reply) String() string { return fmt.Sprintf("%d %s", r.code, trunc(r.body, 160)) }

func trunc(s string, n int) string {
	s = strings.ReplaceAll(s, "\n", " ")
	if len(s) > n {
		return s[:n] + "..."
	}
	return s
}

// call POSTs body to Kong. host, when set, overrides the Host header (Kong routes by it).
func call(t *testing.T, path, token, body string, hdr map[string]string) reply {
	t.Helper()
	return callHost(t, "", path, token, body, hdr)
}

func callHost(t *testing.T, host, path, token, body string, hdr map[string]string) reply {
	t.Helper()
	req, err := http.NewRequest(http.MethodPost, kongURL+path, strings.NewReader(body))
	if err != nil {
		t.Fatal(err)
	}
	req.Header.Set("Content-Type", "application/json")
	if token != "" {
		req.Header.Set("Authorization", "Bearer "+token)
	}
	for k, v := range hdr {
		req.Header.Set(k, v)
	}
	if host != "" {
		req.Host = host
	}
	resp, err := kongClient.Do(req)
	if err != nil {
		t.Fatalf("POST %s: %v", path, err)
	}
	defer resp.Body.Close()
	b, _ := io.ReadAll(resp.Body)
	return reply{resp.StatusCode, resp.Header, string(b)}
}

func msg(model string) string {
	return fmt.Sprintf(`{"model":%q,"max_tokens":8,"messages":[{"role":"user","content":"hi"}]}`, model)
}

func mint(t *testing.T, email string, groups ...string) string {
	t.Helper()
	return mintAud(t, aud, email, groups...)
}

func mintAud(t *testing.T, audience, email string, groups ...string) string {
	t.Helper()
	q := url.Values{"email": {email}, "aud": {audience}}
	if len(groups) > 0 {
		q.Set("groups", strings.Join(groups, ","))
	}
	resp, err := http.Get(mockAURL + "/_uat/mint?" + q.Encode())
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	b, _ := io.ReadAll(resp.Body)
	if resp.StatusCode != 200 {
		t.Fatalf("mint: %d %s", resp.StatusCode, b)
	}
	return string(b)
}

// rec is one request a mock upstream saw.
type rec struct {
	Path    string              `json:"path"`
	Query   string              `json:"query"`
	Headers map[string][]string `json:"headers"`
	Body    string              `json:"body"`
}

func (r rec) h(k string) string {
	for hk, v := range r.Headers {
		if strings.EqualFold(hk, k) && len(v) > 0 {
			return v[0]
		}
	}
	return ""
}

func (r rec) model() string {
	var b struct {
		Model string `json:"model"`
	}
	_ = json.Unmarshal([]byte(r.Body), &b)
	return b.Model
}

func seen(t *testing.T, mock string) []rec {
	t.Helper()
	resp, err := http.Get(mock + "/_uat/requests")
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	var out []rec
	if err := json.NewDecoder(resp.Body).Decode(&out); err != nil {
		t.Fatal(err)
	}
	return out
}

func reset(t *testing.T) {
	t.Helper()
	for _, m := range []string{mockAURL, mockBURL} {
		resp, err := http.Post(m+"/_uat/reset", "text/plain", nil)
		if err != nil {
			t.Fatal(err)
		}
		resp.Body.Close()
	}
}

// who reports which mock (a, b, or "") served the single request just made, and what it saw.
func who(t *testing.T) (string, rec) {
	t.Helper()
	a, b := seen(t, mockAURL), seen(t, mockBURL)
	switch {
	case len(a) == 1 && len(b) == 0:
		return "a", a[0]
	case len(a) == 0 && len(b) == 1:
		return "b", b[0]
	case len(a)+len(b) == 0:
		return "", rec{}
	}
	t.Fatalf("expected at most one upstream hit, got a=%d b=%d", len(a), len(b))
	return "", rec{}
}

// oracle is the library the plugin itself runs: used to pick users in a given cohort and
// to compare, not to produce the expected routing of the system under test by itself.
type oracle struct{ org *policy.Org }

func (o oracle) decide(user string, groups []string, alias string) gateway.Decision {
	return gateway.Decide(o.org, gateway.RequestInfo{UserID: user, Groups: groups, ModelAlias: alias})
}

func (o oracle) find(t *testing.T, groups []string, alias string, pred func(gateway.Decision) bool) string {
	t.Helper()
	for i := 0; i < 20000; i++ {
		u := fmt.Sprintf("user%d@acme.example", i)
		if pred(o.decide(u, groups, alias)) {
			return u
		}
	}
	t.Fatalf("no user matches the predicate (alias %s, groups %v)", alias, groups)
	return ""
}

func variantOf(exp, variant string) func(gateway.Decision) bool {
	return func(d gateway.Decision) bool { return d.Experiment == exp && d.Variant == variant }
}

func kongLogs(t *testing.T) string {
	t.Helper()
	out, err := exec.Command("docker", "compose", "-p", getenv("UAT_PROJECT", "halos-uat-kong"), "logs", "--no-color", "kong").CombinedOutput() //nolint:gosec // test harness
	if err != nil {
		t.Logf("docker compose logs: %v", err)
	}
	return string(out)
}

func serverPost(t *testing.T, path, reason string) int {
	t.Helper()
	body, _ := json.Marshal(map[string]string{"reason": reason})
	req, _ := http.NewRequest(http.MethodPost, serverURL+path, bytes.NewReader(body))
	req.Header.Set("Content-Type", "application/json")
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	_, _ = io.Copy(io.Discard, resp.Body)
	return resp.StatusCode
}

// until polls f every 2s up to d and returns the elapsed time and whether it became true.
func until(d time.Duration, f func() bool) (time.Duration, bool) {
	t0 := time.Now()
	for time.Since(t0) < d {
		if f() {
			return time.Since(t0), true
		}
		time.Sleep(2 * time.Second)
	}
	return time.Since(t0), false
}

// pct returns the p-th percentile (nearest rank) of ds.
func pct(ds []time.Duration, p int) time.Duration {
	s := slices.Clone(ds)
	slices.Sort(s)
	return s[(len(s)*p+99)/100-1]
}

